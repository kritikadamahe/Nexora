"""Reproduce the forecast + replenishment evaluation.

    python -m inventory_painpoints_service.app.forecasting.run_evaluation [--out DIR] [--data DIR]

Writes forecast_metrics.csv, forecast_extras.json, policy_simulation.csv,
backtest_predictions.csv and forecast_evaluation.md. Runtime is a few minutes (the
original-heuristic baseline is recomputed for every test origin).
"""
import argparse
import json
import os
from pathlib import Path

import numpy as np
import pandas as pd

from inventory_painpoints_service.app.data.cleaners.clean_products import clean_products
from inventory_painpoints_service.app.data.cleaners.clean_sales import clean_sales
from inventory_painpoints_service.app.data.cleaners.clean_stores import clean_stores
from inventory_painpoints_service.app.data.loaders.products_loader import load_products
from inventory_painpoints_service.app.data.loaders.sales_loader import load_sales
from inventory_painpoints_service.app.data.loaders.stores_loader import load_stores
from inventory_painpoints_service.app.forecasting.evaluation import run_backtest, write_report
from inventory_painpoints_service.app.forecasting.model import ModelConfig
from inventory_painpoints_service.app.forecasting.panel import build_daily_panel
from inventory_painpoints_service.app.inventory_policy.simulation import simulate

ROOT = Path(__file__).resolve().parents[2]


def load_clean(data_dir):
    products = clean_products(load_products(os.path.join(data_dir, "products.csv")))
    stores = clean_stores(load_stores(os.path.join(data_dir, "stores.csv")))
    sales = clean_sales(load_sales(os.path.join(data_dir, "sales.csv")), products, stores)
    return sales, products


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(ROOT / "datasamplesv2"))
    ap.add_argument("--out", default=str(ROOT / "forecast_evaluation"))
    args = ap.parse_args(argv)

    sales, products = load_clean(args.data)
    cfg = ModelConfig()
    preds, metrics, extras = run_backtest(sales, products, cfg)
    write_report(metrics, extras, args.out)
    out_preds = preds.drop(columns=["base"])
    fl = out_preds.select_dtypes("float").columns
    out_preds[fl] = out_preds[fl].round(4)
    out_preds.to_csv(Path(args.out) / "backtest_predictions.csv", index=False)

    # replenishment simulation over the same out-of-sample weeks
    panel = build_daily_panel(sales)
    pos = {(a, b): i for i, (a, b) in enumerate(zip(panel.keys.product_id, panel.keys.store_id))}
    cost = panel.keys["product_id"].map(products.set_index("product_id")["cost_price"]).to_numpy(float)
    first = int(preds["origin_idx"].min())
    last_origin = int(preds["origin_idx"].max())
    reviews = list(range(first, last_origin - 5, 7))
    sim = simulate(panel.y, preds, pos, reviews, panel.n_days - 1, cost)
    sim.to_csv(Path(args.out) / "policy_simulation.csv", index=False)
    extras["simulation_reviews"] = [str(panel.dates[i].date()) for i in reviews]
    (Path(args.out) / "forecast_extras.json").write_text(json.dumps(extras, indent=2, default=str))
    _write_markdown(metrics, extras, sim, Path(args.out) / "forecast_evaluation.md")
    print(metrics[metrics.fold == "pooled"].round(4).to_string(index=False))
    print(sim.round(4).to_string(index=False))


def _write_markdown(metrics, extras, sim, path):
    pooled = metrics[metrics.fold == "pooled"].set_index("method")
    lines = ["# Forecast and replenishment evaluation (generated)", "",
             "Generated by `python -m inventory_painpoints_service.app.forecasting.run_evaluation`.",
             f"Data: {extras['panel_dates'][0]} to {extras['panel_dates'][1]}, "
             f"{extras['n_series']} product-store series, synthetic.",
             "Target: units demanded over the next 7 days. Out-of-sample: last 12 weeks, three "
             "rolling-origin 4-week blocks, model retrained before each block on data whose "
             "targets were fully observed before the block.", "",
             "## Pooled out-of-sample accuracy", "",
             "| Method | WAPE | MAE (units) | RMSE | Bias | Median series WAPE |", "|---|---|---|---|---|---|"]
    for m, r in pooled.iterrows():
        lines.append(f"| {m} | {r.WAPE:.3f} | {r.MAE:.2f} | {r.RMSE:.1f} | {r.bias_pct:+.3f} | "
                     f"{r.median_series_WAPE:.3f} |")
    iv = extras["interval_p90"]
    lines += ["", f"P90 forecast coverage: {iv['coverage']:.3f} (target {iv['target_coverage']}); "
              f"pinball loss {iv['pinball_loss']:.2f}.", "", "## Paired bootstrap (resampling products)", ""]
    for k, v in extras["paired_bootstrap_WAPE_diff"].items():
        lines.append(f"- WAPE({k.replace('_minus_', ') - WAPE(')}) = {v['diff']:+.4f}, "
                     f"95% CI [{v['ci95'][0]:+.4f}, {v['ci95'][1]:+.4f}]")
    lines += ["", "## Replenishment simulation (same weeks, same starting stock)", "",
              "| Policy | Fill rate | Avg on-hand units | Avg on-hand value at cost | Stock-out series-days |",
              "|---|---|---|---|---|"]
    for _, r in sim.iterrows():
        lines.append(f"| {r.policy} | {r.fill_rate:.3f} | {r.avg_on_hand_units:,.0f} | "
                     f"{r.avg_on_hand_value_at_cost:,.0f} | {int(r.stockout_series_days)} |")
    path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
